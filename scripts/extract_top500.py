#!/usr/bin/env python3
"""Reproduce src/hanzi/data.cljs from the Keats top-500 ordering.

Order source (teaching order, :rank 1-500):
    https://blog.keatschinese.com/the-500-most-commonly-used-chinese-characters/
    The list is saved, one character per line, in scripts/keats500.txt.
    It was extracted from that page's <strong> characters in order
    (500 unique, no duplicates). One character was garbled in a
    browser-text crawl of the page (the 5th character of the
    太/新/比/才/…/夫 row) but is 便 in the page's raw HTML, and
    便 is in the saved list at that position.

Frequency/gloss source (kept, but no longer the ordering):
    MTSU / Jun Da list, decoded to data-raw/mtsu-decoded.txt
    (rank TAB char TAB freq TAB cum-% TAB pinyin TAB English gloss).
    :freq, :cum, :pinyin-mtsu and :english-mtsu come from there;
    :rank here is the Keats position, not the MTSU rank, so that
    the displayed "#N most frequent" matches the teaching order.
    All 500 Keats characters are present in the MTSU file, though
    57 of them are outside the old MTSU top 1000 (e.g. 她 at MTSU
    rank 1330, 确 at 2328).

Character data source:
    skishore/makemeahanzi dictionary.txt and graphics.txt, now
    tracked in data-raw/makemeahanzi/ (see README). All 500 Keats
    characters are present in both files, with matching stroke
    and median counts.

Usage (from the project root):
    python3 scripts/extract_top500.py
    # writes src/hanzi/data.cljs and data-raw/top500.json
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
RAW = ROOT / "data-raw"


def cljs_str(s):
    # JSON string escaping is valid ClojureScript string escaping.
    return json.dumps(s, ensure_ascii=False)


def cljs_vec_strs(xs):
    return "[" + " ".join(cljs_str(x) for x in xs) + "]"


def cljs_medians(medians):
    parts = []
    for med in medians:
        parts.append("[" + " ".join(f"[{x} {y}]" for x, y in med) + "]")
    return "[" + " ".join(parts) + "]"


def main():
    keats = [ln.strip() for ln in (ROOT / "scripts" / "keats500.txt").read_text(encoding="utf-8").splitlines() if ln.strip()]
    assert len(keats) == 500 and len(set(keats)) == 500, len(keats)

    mtsu = {}
    for line in (RAW / "mtsu-decoded.txt").read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        parts = line.split("\t")
        parts = parts + [""] * (6 - len(parts))
        _rank, ch, freq, cum, pinyin, eng = parts[:6]
        mtsu[ch] = {"freq": int(freq), "cum": float(cum), "pinyin_mtsu": pinyin, "english_mtsu": eng}

    makemea = RAW / "makemeahanzi"
    dic = {}
    for line in (makemea / "dictionary.txt").read_text(encoding="utf-8").splitlines():
        j = json.loads(line)
        dic[j["character"]] = j
    gra = {}
    for line in (makemea / "graphics.txt").read_text(encoding="utf-8").splitlines():
        j = json.loads(line)
        gra[j["character"]] = j

    out = []
    for i, ch in enumerate(keats, start=1):
        assert ch in mtsu, f"missing from MTSU: {ch}"
        assert ch in dic, f"missing from dictionary: {ch}"
        assert ch in gra, f"missing from graphics: {ch}"
        d, g = dic[ch], gra[ch]
        assert len(g["strokes"]) == len(g["medians"]), ch
        m = mtsu[ch]
        out.append({
            "rank": i, "char": ch, "freq": m["freq"], "cum": m["cum"],
            "pinyin_mtsu": m["pinyin_mtsu"], "english_mtsu": m["english_mtsu"],
            "pinyin": d.get("pinyin", []), "definition": d.get("definition", ""),
            "radical": d.get("radical", ""), "decomposition": d.get("decomposition", ""),
            "strokes": g["strokes"], "medians": g["medians"],
        })

    (RAW / "top500.json").write_text(
        json.dumps(out, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")

    lines = []
    lines.append("(ns hanzi.data (:refer-clojure :exclude [chars]))")
    lines.append("")
    lines.append(";; Top 500 characters, in Keats School order.")
    lines.append(";; Generated by scripts/extract_top500.py from:")
    lines.append(";;  - https://blog.keatschinese.com/the-500-most-commonly-used-chinese-characters/  (order, :rank 1-500)")
    lines.append(";;  - MTSU / Jun Da list (frequency, MTSU pinyin/gloss, kept as :freq/:cum/:pinyin-mtsu/:english-mtsu)")
    lines.append(";;  - skishore/makemeahanzi dictionary.txt (pinyin with tones, definition, radical, decomposition)")
    lines.append(";;  - skishore/makemeahanzi graphics.txt (strokes = SVG paths, medians = stroke centrelines)")
    lines.append(";; Coordinates are makemeahanzi originals: display y = 900 - y. See hanzi.strokes/display-median.")
    lines.append("(def chars")
    lines.append("[")
    for e in out:
        entry = (
            f" {{:rank {e['rank']} :char {cljs_str(e['char'])} :freq {e['freq']} :cum {e['cum']}"
            f" :pinyin-mtsu {cljs_str(e['pinyin_mtsu'])} :english-mtsu {cljs_str(e['english_mtsu'])}"
            f" :pinyin {cljs_vec_strs(e['pinyin'])} :definition {cljs_str(e['definition'])}"
            f" :radical {cljs_str(e['radical'])} :decomposition {cljs_str(e['decomposition'])}"
            f" :strokes {cljs_vec_strs(e['strokes'])} :medians {cljs_medians(e['medians'])}}}"
        )
        lines.append(entry)
    lines.append("])")
    (ROOT / "src" / "hanzi" / "data.cljs").write_text("\n".join(lines) + "\n", encoding="utf-8")

    total_strokes = sum(len(e["strokes"]) for e in out)
    print(f"wrote {len(out)} characters, {total_strokes} strokes, to src/hanzi/data.cljs")
    print(f"first: {out[0]['char']} (Keats #1), last: {out[-1]['char']} (Keats #500)")


if __name__ == "__main__":
    main()
